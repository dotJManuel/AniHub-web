const DICT: Record<Lang, Record<Key, string>> = { es, en };

const PREF_KEY = 'pref:lang';

// Idioma de la región: cualquier variante de español -> 'es'; el resto -> 'en'.
export function detectLang(): Lang {
  const l = (typeof navigator !== 'undefined' ? navigator.languages?.[0] || navigator.language : '') || 'en';
  return l.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function getLangPref(): LangPref {
  try {
    const v = localStorage.getItem(PREF_KEY);
    return v === 'es' || v === 'en' ? v : 'system';
  } catch {
    return 'system';
  }
}

export const resolveLang = (pref: LangPref = getLangPref()): Lang => (pref === 'system' ? detectLang() : pref);

export function format(str: string, params?: Record<string, string | number>): string {
  return params ? str.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`)) : str;
}

export const translate = (lang: Lang, key: Key, params?: Record<string, string | number>) => format(DICT[lang][key], params);

// Para código fuera de React (errores, etiquetas): usa el idioma vigente en ese momento.
export const tr = (key: Key, params?: Record<string, string | number>) => translate(resolveLang(), key, params);

export const hasKey = (k: string): k is Key => k in es;
